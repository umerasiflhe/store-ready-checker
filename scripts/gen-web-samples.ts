import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repoRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const fixturesDir = join(repoRoot, 'fixtures/files');
const destPath = join(repoRoot, 'apps/web/src/samples.data.ts');

/**
 * "Try a sample" buttons must never fetch anything (CSP `connect-src 'none'`, and ESLint bans
 * `fetch`/XHR in `apps/web/src/**`), so the bytes are inlined as base64 at build time instead.
 * One ready iOS sample, one ready Android sample, and one blocked Android sample (which doubles
 * as the e2e fixture for the "as-of flips the 16K finding across 2027-02-01" test).
 */
const SAMPLES = [
  {
    id: 'ios-ready',
    label: 'iOS — ready to upload',
    fileName: 'ios-passing-app.ipa',
    kind: 'ipa' as const,
  },
  {
    id: 'android-ready',
    label: 'Android — ready to upload',
    fileName: 'android-aab-passing.aab',
    kind: 'aab' as const,
  },
  {
    id: 'android-blocked',
    label: 'Android — blocked (16 KB page alignment)',
    fileName: 'android-aab-16k-load-misaligned.aab',
    kind: 'aab' as const,
  },
];

function generate(): string {
  const entries = SAMPLES.map((sample) => {
    const bytes = readFileSync(join(fixturesDir, sample.fileName));
    const base64 = bytes.toString('base64');
    return `  {
    id: '${sample.id}',
    label: '${sample.label}',
    fileName: '${sample.fileName}',
    kind: '${sample.kind}',
    base64:
      '${base64}',
  },`;
  });

  return `// Generated by scripts/gen-web-samples.ts from fixtures/files/ — do not edit by hand.
// Run \`npm run gen:web-samples\` after changing which fixtures back the sample buttons.

export interface SampleFixture {
  readonly id: string;
  readonly label: string;
  readonly fileName: string;
  readonly kind: 'ipa' | 'aab' | 'apk';
  readonly base64: string;
}

export const SAMPLES: readonly SampleFixture[] = [
${entries.join('\n')}
];
`;
}

function main(): void {
  const checkOnly = process.argv.includes('--check');
  const generated = generate();

  if (checkOnly) {
    const existing = (() => {
      try {
        return readFileSync(destPath, 'utf8');
      } catch {
        return undefined;
      }
    })();
    if (existing !== generated) {
      console.error(`${destPath} is stale. Run: npm run gen:web-samples`);
      process.exit(1);
    }
    console.log('apps/web/src/samples.data.ts is up to date.');
    return;
  }

  writeFileSync(destPath, generated);
  console.log(`Wrote ${String(SAMPLES.length)} sample(s) to ${destPath}.`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  main();
}

export {};

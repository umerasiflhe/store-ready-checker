import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import * as Ajv2020Module from 'ajv/dist/2020.js';
import ajvFormatsDefault from 'ajv-formats';
import type { FormatsPlugin } from 'ajv-formats';
import { format as prettierFormat, resolveConfig as resolvePrettierConfig } from 'prettier';

const Ajv2020 = Ajv2020Module.Ajv2020;
// ajv-formats' default export resolves to the whole module namespace under
// `module: NodeNext` + esModuleInterop; the runtime value is the plugin function.
const addFormats = ajvFormatsDefault as unknown as FormatsPlugin;

const repoRoot = dirname(dirname(fileURLToPath(import.meta.url)));

interface RuleSource {
  title: string;
  url: string;
  retrieved: string;
}
interface RuleTimelineEntry {
  from: string;
  severity: 'error' | 'warning' | 'info';
  note?: string;
  formFactors?: string[];
}
interface Rule {
  id: string;
  platform: 'ios' | 'android';
  title: string;
  confidence?: 'certain' | 'heuristic';
  timeline: RuleTimelineEntry[];
  sources: RuleSource[];
  fix: string[];
}
interface RulesData {
  rulesVersion: string;
  rules: Rule[];
}

function loadRules(): RulesData {
  const rulesPath = join(repoRoot, 'rules/rules.json');
  const schemaPath = join(repoRoot, 'schema/rules.schema.json');
  const data = JSON.parse(readFileSync(rulesPath, 'utf8')) as RulesData;
  const schema = JSON.parse(readFileSync(schemaPath, 'utf8')) as Record<string, unknown>;

  const ajv = new Ajv2020({ allErrors: true, strict: true });
  addFormats(ajv);
  const validate = ajv.compile(schema);
  if (!validate(data)) {
    const messages = (validate.errors ?? []).map(
      (error) => `${error.instancePath} ${error.message ?? ''}`,
    );
    throw new Error(
      `rules/rules.json does not match schema/rules.schema.json:\n${messages.join('\n')}`,
    );
  }
  return data;
}

function earliestEnforcedDate(rule: Rule): string {
  return rule.timeline[0]?.from ?? '—';
}

function renderTable(rules: Rule[]): string {
  const header = '| ID | Platform | Check | In force from |\n| --- | --- | --- | --- |';
  const rows = rules.map(
    (rule) =>
      `| \`${rule.id}\` | ${rule.platform} | ${rule.title} | ${earliestEnforcedDate(rule)} |`,
  );
  return [header, ...rows].join('\n');
}

function renderRuleSection(rule: Rule): string {
  const timeline = rule.timeline
    .map(
      (entry) =>
        `- **${entry.severity}** from ${entry.from}${
          entry.formFactors ? ` (${entry.formFactors.join(', ')} only)` : ''
        }${entry.note ? ` — ${entry.note}` : ''}`,
    )
    .join('\n');
  const sources =
    rule.sources.length > 0
      ? rule.sources
          .map((source) => `- [${source.title}](${source.url}) (retrieved ${source.retrieved})`)
          .join('\n')
      : '- none (tool-only informational note)';
  const fix = rule.fix.map((step) => `- ${step}`).join('\n');
  const confidence = rule.confidence ? ` · confidence: ${rule.confidence}` : '';

  return [
    `## \`${rule.id}\` — ${rule.title}`,
    '',
    `Platform: ${rule.platform}${confidence}`,
    '',
    'Severity timeline:',
    '',
    timeline,
    '',
    'Sources:',
    '',
    sources,
    '',
    'Fix:',
    '',
    fix,
  ].join('\n');
}

function renderDoc(data: RulesData): string {
  const sections = data.rules.map(renderRuleSection).join('\n\n');
  return [
    '<!-- Generated by scripts/gen-rules-doc.ts from rules/rules.json. Do not edit by hand. -->',
    '',
    '# Rules',
    '',
    `Rules version: \`${data.rulesVersion}\`. Every rule is evaluated "as of" a chosen date against its severity timeline below.`,
    '',
    renderTable(data.rules),
    '',
    sections,
    '',
  ].join('\n');
}

function replaceReadmeBlock(readme: string, table: string): string {
  const start = '<!-- rules:start -->';
  const end = '<!-- rules:end -->';
  const startIndex = readme.indexOf(start);
  const endIndex = readme.indexOf(end);
  if (startIndex === -1 || endIndex === -1 || endIndex < startIndex) {
    throw new Error('README.md is missing the <!-- rules:start --> / <!-- rules:end --> markers');
  }
  const before = readme.slice(0, startIndex + start.length);
  const after = readme.slice(endIndex);
  return `${before}\n\n${table}\n\n${after}`;
}

async function formatMarkdown(content: string): Promise<string> {
  const config = (await resolvePrettierConfig(repoRoot)) ?? {};
  return prettierFormat(content, { ...config, parser: 'markdown' });
}

async function main(): Promise<void> {
  const checkOnly = process.argv.includes('--check');
  const data = loadRules();

  const rulesDocPath = join(repoRoot, 'docs/RULES.md');
  const readmePath = join(repoRoot, 'README.md');

  const newRulesDoc = await formatMarkdown(renderDoc(data));
  const currentReadme = readFileSync(readmePath, 'utf8');
  const newReadme = await formatMarkdown(
    replaceReadmeBlock(currentReadme, renderTable(data.rules)),
  );
  const currentRulesDoc = existsSync(rulesDocPath) ? readFileSync(rulesDocPath, 'utf8') : undefined;

  const stale = currentRulesDoc !== newRulesDoc || currentReadme !== newReadme;

  if (checkOnly) {
    if (stale) {
      console.error('docs/RULES.md or the README rules block is stale. Run: npm run rules:doc');
      process.exit(1);
    }
    console.log('docs/RULES.md and the README rules block are up to date.');
    return;
  }

  writeFileSync(rulesDocPath, newRulesDoc);
  writeFileSync(readmePath, newReadme);
  console.log('Regenerated docs/RULES.md and the README rules block.');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  await main();
}

export { loadRules, renderTable, renderDoc, replaceReadmeBlock, formatMarkdown };
